_TAIL = frozenset("っッー～~゛゜ﾞﾟぁぃぅぇぉァィゥェォんン")
_PROLONG_RE = re.compile(r"[ー～〜~]+")
_K2H = {chr(_o + 0x60): chr(_o) for _o in range(0x3041, 0x3097)}


def is_blocked(text: str) -> bool:
    """该串是否含实词词根。

    匹配规则：
      长度 1~2 的词根：【整串相等】或【词根 + 纯尾记号】才拦
        （いいっ 含 いい+っ → 拦；いいぞ 含 いい+ぞ → 拦）
      长度 >= 3 的词根：【含它】就拦
    同时对剥除词内波浪号/长音符后的紧凑串及片假名→平假名转写串做对称校验，
    防止「に～～い」「さ～ん」「ハーイ」「ネー」「イェーイ」等漏网。
    """
    # 实词词根（词根+尾记号也拦）
    _REAL = {
        "もう", "もー", "はい", "ぎゅ", "いえ", "おう", "こう", "こー", "そう", "そー",
        "どう", "どー", "いい", "ねえ", "ねー", "まあ", "まー",
        "いち", "にい", "にぃ", "さん", "よん", "ごお", "ろく", "なな", "はち",
    }
    hira = "".join(_K2H.get(c, c) for c in text)
    cands_list = []
    for base in (text, hira):
        if base and base not in cands_list:
            cands_list.append(base)
        compact = _PROLONG_RE.sub("", base)
        if compact and compact not in cands_list:
            cands_list.append(compact)
    for cand in cands_list:
        if not cand:
            continue
        for r in _ROOTS:
            if len(r) <= 2:
                if cand == r:
                    return True
                # 实词词根 + 纯尾记号（いいっ / もうっ / はいっ / ぎゅ～～～ / に～～いっ）
                if r in _REAL and cand.startswith(r):
                    rest = cand[len(r):]
                    if rest and all(c in _TAIL for c in rest):
                        return True
            elif r in cand:
                return True
    return False


